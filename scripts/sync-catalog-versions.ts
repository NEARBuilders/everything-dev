#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  readWorkspaceCatalog,
  writeWorkspaceCatalog,
} from "../packages/everything-dev/src/services/workspace/catalog";

const FRAMEWORK_PACKAGES = ["everything-dev", "every-plugin", "better-near-auth"];

const MIRROR_PATH = join(
  import.meta.dirname,
  "..",
  "packages/everything-dev/src/services/scaffold/upgrade-audit/steps/v2-catalog.ts",
);

const MIRROR_HEADER = `// GENERATED by scripts/sync-catalog-versions.ts — the v1→v2 migration's catalog
// baseline, a verbatim mirror of the parent pnpm-workspace.yaml catalog. Do not
// edit by hand; regenerate via pnpm run sync-catalog.

export const V2_CATALOG: Readonly<Record<string, string>> = `;

const rootDir = join(import.meta.dirname, "..");

const catalog = readWorkspaceCatalog(rootDir);
if (Object.keys(catalog).length === 0) {
  console.error("No catalog found in pnpm-workspace.yaml");
  process.exit(1);
}

const quote = (value: string) =>
  /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(value) ? value : JSON.stringify(value);
const catalogRows = (rows: Record<string, string>) =>
  Object.entries(rows)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([key, version]) => `  ${quote(key)}: ${quote(version)},`)
    .join("\n");

const mirrorContent = (rows: Record<string, string>) =>
  `${MIRROR_HEADER}{\n${catalogRows(rows)}\n};\n`;

const emitCatalogMirror = (rows: Record<string, string>) => {
  const content = mirrorContent(rows);
  writeFileSync(MIRROR_PATH, content);
  const written = readFileSync(MIRROR_PATH, "utf-8");
  if (written !== content) {
    throw new Error(
      "v2-catalog.ts self-check failed: re-read content diverged from written content",
    );
  }
  console.log(`Catalog mirror emitted: ${Object.keys(rows).length} rows.`);
};

let changed = false;

for (const packageName of FRAMEWORK_PACKAGES) {
  const pkgJsonPath = join(rootDir, "packages", packageName, "package.json");
  let pkgVersion: string | undefined;
  try {
    const pkg = JSON.parse(readFileSync(pkgJsonPath, "utf-8")) as { version?: string };
    pkgVersion = pkg.version;
  } catch {
    console.warn(`Could not read ${pkgJsonPath}, skipping ${packageName}`);
    continue;
  }

  if (!pkgVersion) {
    console.warn(`No version field in ${pkgJsonPath}, skipping ${packageName}`);
    continue;
  }

  const newValue = `^${pkgVersion}`;
  if (catalog[packageName] !== newValue) {
    console.log(`${packageName}: ${catalog[packageName]} → ${newValue}`);
    catalog[packageName] = newValue;
    changed = true;
  }
}

if (changed) {
  writeWorkspaceCatalog(rootDir, catalog);
  console.log("Catalog versions synced.");
} else {
  console.log("Catalog versions already up to date.");
}

const mirror = readWorkspaceCatalog(rootDir);
emitCatalogMirror(mirror);
